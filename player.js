/* ═══════════════════════════════════════════════════
   FETCH TRACKS
   ─────────────────────────────────────────────────
   Tries two sources in order:

   1. GET /tracks  — local python server (server.py)
      Scans folders live. Works on localhost only.

   2. GET tracks.json — static file
      Generated by generate_tracks.py.
      Works on localhost AND on GitHub Pages.

   How to use:
   ─ Locally  : run  python3 server.py
   ─ GitHub   : run  python3 generate_tracks.py
                then  git add tracks.json && git push
═══════════════════════════════════════════════════ */
async function fetchTracks() {
  /* ── Try 1: live server endpoint ── */
  try {
    const res = await fetch('/tracks', { cache: 'no-store' });
    if (res.ok) {
      const data = await res.json();
      for (const theme of Object.keys(data)) {
        THEME_TRACKS[theme] = data[theme];
      }
      const total = Object.values(THEME_TRACKS).flat().length;
      console.log(`Ehsaas: loaded ${total} tracks from /tracks (live server)`);
      return;
    }
  } catch (_) {
    /* server not running — fall through to tracks.json */
  }

  /* ── Try 2: static tracks.json (GitHub Pages / file open) ── */
  try {
    const res = await fetch('tracks.json', { cache: 'no-store' });
    if (res.ok) {
      const data = await res.json();
      for (const theme of Object.keys(data)) {
        THEME_TRACKS[theme] = data[theme];
      }
      const total = Object.values(THEME_TRACKS).flat().length;
      console.log(`Ehsaas: loaded ${total} tracks from tracks.json (static)`);
      return;
    }
  } catch (_) { /* no tracks.json either */ }

  /* ── Both failed: show empty state ── */
  console.warn(
    'Ehsaas: could not load tracks.\n' +
    'Locally  → run: python3 server.py\n' +
    'GitHub   → run: python3 generate_tracks.py  then push tracks.json'
  );
}

