function fmt(seconds) {
  if (seconds === undefined || seconds === null) return '0:00';
  if (isNaN(seconds) || !isFinite(seconds))      return '0:00';
  const m = Math.floor(seconds / 60);
  const s = Math.floor(seconds % 60);
  return `${m}:${String(s).padStart(2, '0')}`;
}

